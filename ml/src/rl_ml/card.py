"""Generate ``docs/ml/RESULTS.md`` and ``docs/ml/MODEL_CARD.md`` from real run JSON.

Every number in both documents is read from ``docs/ml/results/<variant>.json`` (written by
:mod:`rl_ml.train` from a real run). Synthetic runs are rejected. When no real run exists the
documents say so instead of showing numbers.

    python -m rl_ml.card [--docs-dir docs/ml]
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any, Final

from rl_ml.data import DATA_SOURCE, DATASET_MD5

PRIMARY: Final = "failed_or_errored"
SENSITIVITY: Final = "errored_excluded"
TBD: Final = "TBD — measured in M4 once the feature mart exists"
GENERATED: Final = (
    "> Generated by `python -m rl_ml.card` from `docs/ml/results/*.json` (real runs only). "
    "Do not edit by hand: re-run training or the generator."
)


class SyntheticResultsError(ValueError):
    pass


# ---------------------------------------------------------------- formatting
def f(x: Any, nd: int = 3) -> str:
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "—"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, int):
        return f"{x:,}"
    return f"{x:.{nd}f}"


def pct(x: Any, nd: int = 1) -> str:
    return "—" if x is None else f"{100 * float(x):.{nd}f}%"


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def date(s: str | None) -> str:
    return "—" if not s else s[:10]


# ---------------------------------------------------------------- loading
def load_results(docs_dir: Path) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for variant in (PRIMARY, SENSITIVITY):
        p = docs_dir / "results" / f"{variant}.json"
        if not p.is_file():
            continue
        r = json.loads(p.read_text())
        if r["data"].get("synthetic") or r["data"].get("source") != DATA_SOURCE:
            raise SyntheticResultsError(f"{p} is not a real-data run; refusing to publish it")
        if r["data"].get("dataset_md5") != DATASET_MD5:
            raise SyntheticResultsError(f"{p} has dataset md5 {r['data'].get('dataset_md5')}")
        out[variant] = r
    return out


def verdict(roc_auc: float | None) -> str:
    """Plain-language discrimination level from ROC-AUC (independent of the base rate).

    Lift over the base rate is shown next to it, but lift grows as the base rate shrinks, so it is
    not used for the wording.
    """
    if roc_auc is None:
        return "unknown"
    if roc_auc < 0.6:
        return "weak (close to chance)"
    if roc_auc < 0.7:
        return "modest"
    if roc_auc < 0.8:
        return "moderate"
    return "strong"


def _display(r: dict[str, Any], name: str) -> str:
    return next((c["display"] for c in r["candidates"] if c["name"] == name), name)


def _key_params(c: dict[str, Any]) -> str:
    p = c["params"]
    if c["name"].startswith("xgboost"):
        keys = (
            "max_depth",
            "learning_rate",
            "n_estimators",
            "min_child_weight",
            "subsample",
            "colsample_bytree",
        )
        return ", ".join(
            f"{k}={f(p[k], 3) if isinstance(p[k], float) else p[k]}" for k in keys if k in p
        )
    return (
        ", ".join(f"{k}={v if not isinstance(v, float) else f(v, 3)}" for k, v in p.items()) or "—"
    )


# ---------------------------------------------------------------- RESULTS.md
def _headline(r: dict[str, Any]) -> list[str]:
    t = r["test"]["final"]
    ci = t.get("pr_auc_ci95_project_bootstrap") or {}
    heur = r["test"]["reference_candidates"].get("heuristic_rule", {})
    lines = [
        f"- On the untouched chronological test set ({f(t['n'])} builds, failure base rate "
        f"{f(t['base_rate'])}), the final model (**{r['selection']['display']}**, chosen by validation "
        f"PR-AUC) reaches **PR-AUC {f(t['pr_auc'])}** (95% project-bootstrap CI {f(ci.get('low'))}–"
        f"{f(ci.get('high'))}; {f(t['pr_auc_over_base_rate'], 2)}× the base rate) and ROC-AUC "
        f"{f(t['roc_auc'])}: **{verdict(t['roc_auc'])}** discrimination overall.",
        f"- Baselines on the same rows: heuristic rule (previous build failed OR churn > p90) PR-AUC "
        f"{f(heur.get('pr_auc'))}; majority class "
        f"{f(r['test']['reference_candidates'].get('majority_class', {}).get('pr_auc'))}.",
        f"- The top 10% highest-risk builds fail at {pct(t['precision_at_top_10pct'])} "
        f"(lift {f(t['lift_at_top_10pct'], 2)}× over the base rate).",
    ]
    sl = (r["test"].get("by_previous_outcome") or {}).get("previous_passed")
    if sl and sl.get("pr_auc") is not None:
        hp = (sl.get("reference_pr_auc") or {}).get("heuristic_rule")
        persistence = sl["roc_auc"] < t["roc_auc"] - 0.05
        lead = (
            "- Much of the overall signal is **persistence** (a broken build tends to stay broken). "
            if persistence
            else "- Discrimination holds up without the persistence effect. "
        )
        lines.append(
            lead + f"After a passing build ({pct(sl['share_of_rows'])} of test builds, base rate "
            f"{f(sl['base_rate'])}) the model reaches PR-AUC {f(sl['pr_auc'])} "
            f"({f(sl['pr_auc_over_base_rate'], 2)}× base; heuristic {f(hp)}) and ROC-AUC "
            f"{f(sl['roc_auc'])} (**{verdict(sl['roc_auc'])}**); its top 10% of those builds fail at "
            f"{pct(sl['precision_at_top_10pct'])}"
            + (": predicting *new* breakage is much harder." if persistence else ".")
        )
    cold = r["test"]["cold_start"]
    nh = r["test"].get("cold_start_no_history_model")
    lines += [
        f"- Without build history (cold start, history masked) PR-AUC is {f(cold['pr_auc'])} "
        f"({f(cold['pr_auc_over_base_rate'], 2)}× base) and ROC-AUC {f(cold['roc_auc'])}: "
        f"**{verdict(cold['roc_auc'])}**"
        + (
            f"; a model trained without history features reaches PR-AUC {f(nh['pr_auc'])} / "
            f"ROC-AUC {f(nh['roc_auc'])} (**{verdict(nh['roc_auc'])}**)."
            if nh
            else "."
        ),
        f"- Calibrated probability exposed: **{'yes' if r['test']['probability_exposed'] else 'no'}** "
        f"(ADR-0012 gate, {r['test']['calibration']['selected_method']} calibration).",
    ]
    return lines


def _persistence_section(r: dict[str, Any]) -> list[str]:
    sl = r["test"].get("by_previous_outcome")
    if not sl:
        return ["Not computed in this run."]
    names = {
        "previous_passed": "previous finished build passed",
        "previous_failed": "previous finished build failed",
        "no_finished_history": "no finished history yet",
    }
    rows = []
    for k, label in names.items():
        m = sl.get(k, {})
        ref = m.get("reference_pr_auc", {})
        rows.append(
            [
                label,
                f(m.get("n")),
                pct(m.get("share_of_rows")),
                f(m.get("base_rate")),
                f(m.get("pr_auc")),
                f(m.get("roc_auc")),
                f(m.get("pr_auc_over_base_rate"), 2),
                f(ref.get("heuristic_rule")),
                f(ref.get("logistic_regression")),
            ]
        )
    return [
        "Test rows split by the outcome of the previous *finished* build of the same project. The "
        "failure rate after a failed build is far higher than after a passing one, so a large part of "
        'the overall PR-AUC is "broken stays broken". The *previous passed* slice is the product-relevant '
        "question of predicting new breakage from the change itself.",
        "",
        table(
            [
                "slice",
                "builds",
                "share",
                "base rate",
                "PR-AUC",
                "ROC-AUC",
                "PR-AUC / base",
                "heuristic PR-AUC",
                "logistic PR-AUC",
            ],
            rows,
        ),
    ]


def _data_section(r: dict[str, Any]) -> list[str]:
    cb = r["class_balance"]
    rows = []
    for s in ("train", "validation", "test", "all"):
        e = cb[s]
        rows.append(
            [
                s,
                f(e["rows"]),
                f(e["positives"]),
                f(e["base_rate"]),
                f(e["projects"]),
                f"{date(e.get('started_at_min'))} → {date(e.get('started_at_max'))}",
            ]
        )
    lines = [
        f"- Label: {r['label_definition']}.",
        f"- Feature mart run_id `{r['data']['features_run_id']}`, FEATURE_SCHEMA_VERSION "
        f"`{r['data']['feature_schema_version']}`, dataset md5 `{r['data']['dataset_md5']}`.",
        *[
            f"- Mart file `{x['key'].rsplit('/', 1)[-1]}`: {f(x['rows'])} rows, sha256 `{x['sha256']}`."
            for x in r["data"].get("mart_files", [])
        ],
        "- Split: the mart's global chronological 70/15/15 split (cut dates below).",
        "",
        table(
            ["split", "builds", "failures", "base rate", "projects", "started_at range (UTC)"], rows
        ),
    ]
    st = cb["all"].get("status_counts")
    if st:
        lines += [
            "",
            "Status counts (all rows): " + ", ".join(f"{k} {f(v)}" for k, v in st.items()) + ".",
        ]
    for n in r["data"].get("notes", []):
        lines.append(f"- Note: {n}.")
    return lines


NULL_BY_DESIGN: Final = {
    "num_commits_in_push": "no push-level commit count in the 2016 release",
    "description_complexity": "PR title/description tagged uncertain (text may postdate the build)",
    "project_age_days": "from repo_age_days; gh_first_commit_created_at is a copy of tr_started_at",
}


def _dropped_features(r: dict[str, Any]) -> list[str]:
    dropped = r.get("feature_coverage", {}).get("dropped_from_model_inputs", [])
    if not dropped:
        return ["No feature is null for every training row; all features are model inputs."]
    rows = [[f"`{n}`", NULL_BY_DESIGN.get(n, "null for every row of this mart")] for n in dropped]
    return [
        "Features that are null for every training row are **dropped from all model inputs** "
        "(NULL by design in the mart, see `data/dbt/models/ml/mart_build_inputs.sql`):",
        "",
        table(["feature", "why it is null"], rows),
    ]


def _candidates_section(r: dict[str, Any]) -> list[str]:
    rows = []
    for c in r["candidates"]:
        mark = " **(final)**" if c["name"] == r["selection"]["final_model"] else ""
        rows.append(
            [
                c["display"] + mark,
                f(c["features"]),
                f(c["val_pr_auc"]),
                f(c["val_roc_auc"]),
                _key_params(c),
                f(c["fit_seconds"], 1),
            ]
        )
    tf = r["time_features"]
    lines = [
        table(
            ["model", "features", "val PR-AUC", "val ROC-AUC", "key parameters", "fit / search s"],
            rows,
        ),
        "",
    ]
    if "val_pr_auc_with" in tf:
        lines.append(
            f"Time-of-week features (hour-of-week sin/cos): XGBoost val PR-AUC without {f(tf['val_pr_auc_without'], 4)}, "
            f"with {f(tf['val_pr_auc_with'], 4)} (Δ {tf['delta']:+.4f}, {tf['trials_each']} Optuna trials each) → "
            f"time features **{'kept' if tf['time_features_used'] else 'not used'}**."
        )
    lines.append(
        f"Final model: **{r['selection']['display']}** — highest validation PR-AUC among "
        f"{', '.join(_display(r, n) for n in r['selection']['eligible'])}; selection locked at "
        f"{r['selection']['locked_at']} before the test set was opened."
    )
    others = sorted(
        (
            c
            for c in r["candidates"]
            if c["name"] in r["selection"]["eligible"]
            and c["name"] != r["selection"]["final_model"]
        ),
        key=lambda c: -c["val_pr_auc"],
    )
    if others:
        margin = r["selection"]["val_pr_auc"] - others[0]["val_pr_auc"]
        lines.append(
            f"Runner-up: {others[0]['display']} (val PR-AUC {f(others[0]['val_pr_auc'], 4)}, margin "
            f"{margin:.4f})"
            + (
                " — effectively a tie; the tree models are interchangeable here."
                if margin < 0.01
                else "."
            )
        )
    return lines


def _test_section(r: dict[str, Any]) -> list[str]:
    t = r["test"]
    fm = t["final"]
    at = fm["at_threshold"]
    cm = at["confusion_matrix"]
    ci = fm.get("pr_auc_ci95_project_bootstrap") or {}
    rci = fm.get("roc_auc_ci95_project_bootstrap") or {}
    lines = [
        f"Test-set evaluations in this run: **{t['evaluations']}** (guarded; access log: "
        f"{t['access_log'][0]['purpose'] if t['access_log'] else '—'}).",
        "",
        table(
            ["metric", "value"],
            [
                [
                    "PR-AUC (average precision)",
                    f"{f(fm['pr_auc'])} (95% CI {f(ci.get('low'))}–{f(ci.get('high'))})",
                ],
                [
                    "ROC-AUC",
                    f"{f(fm['roc_auc'])} (95% CI {f(rci.get('low'))}–{f(rci.get('high'))})",
                ],
                ["base rate", f(fm["base_rate"])],
                ["PR-AUC / base rate", f(fm["pr_auc_over_base_rate"], 2)],
                ["precision @ top 10%", f(fm["precision_at_top_10pct"])],
                ["lift @ top 10%", f(fm["lift_at_top_10pct"], 2)],
                [
                    f"threshold (max F1 on validation) = {f(at['threshold'], 4)}",
                    f"precision {f(at['precision'])}, recall {f(at['recall'])}, F1 {f(at['f1'])}, flags {pct(at['flagged_share'])} of builds",
                ],
                [
                    "confusion matrix",
                    f"TP {f(cm['tp'])} · FP {f(cm['fp'])} · FN {f(cm['fn'])} · TN {f(cm['tn'])}",
                ],
                ["Brier score (selected calibrator)", f(t["calibration"]["gate"]["brier"])],
            ],
        ),
        "",
        "CIs resample whole projects (builds within a project are correlated).",
        "",
        "All candidates on the same test rows — reference only, computed in the same single pass "
        "after the final model was locked; never used for selection:",
        "",
    ]
    rows = []
    for name, m in t["reference_candidates"].items():
        rows.append(
            [_display(r, name), f(m["pr_auc"]), f(m["roc_auc"]), f(m["lift_at_top_10pct"], 2)]
        )
    lines.append(table(["model", "test PR-AUC", "test ROC-AUC", "lift @ top 10%"], rows))
    return lines


def _calibration_section(r: dict[str, Any]) -> list[str]:
    cal = r["test"]["calibration"]
    sel = cal["selected_method"]
    gates = {sel: cal["gate"]} | cal["other_method_informational"]
    rows = []
    for m, g in gates.items():
        c = g["checks"]
        rows.append(
            [
                m + (" (selected on validation)" if m == sel else " (informational)"),
                f"{f(g['ece_10_equal_mass'], 4)} {'✓' if c['ece_le_0.05'] else '✗'}",
                f"{f(g['brier_skill_score'], 4)} {'✓' if c['brier_skill_gt_0'] else '✗'}",
                f"{f(g['calibration_slope'], 3)} {'✓' if c['slope_in_0.8_1.2'] else '✗'}",
                f(g["calibration_intercept"], 3),
                "PASS" if g["passed"] else "FAIL",
            ]
        )
    vsel = r["validation"]["calibration_method_selection"]
    lines = [
        "Both calibrators are fitted on validation only. The gate is applied to the method chosen "
        "on validation (5-fold CV Brier inside validation: "
        + ", ".join(f"{k} {f(v, 5)}" for k, v in vsel["cv_brier"].items())
        + f" → **{sel}**). Thresholds (ADR-0012, fixed before results): ECE ≤ 0.05, Brier skill > 0 "
        "(reference = the test set's own failure rate, the stricter choice), slope in [0.8, 1.2].",
        "",
        table(["method", "ECE (10 equal-mass)", "Brier skill", "slope", "intercept", "gate"], rows),
        "",
        f"**Outcome: probability is {'EXPOSED' if r['test']['probability_exposed'] else 'NOT exposed (API returns null)'}.**",
        "",
        "Reliability (selected method, test, 10 equal-mass bins):",
        "",
        table(
            ["bin", "mean predicted", "observed rate", "n"],
            [
                [str(i + 1), f(b["p_mean"]), f(b["observed_rate"]), f(b["n"])]
                for i, b in enumerate(cal["gate"]["reliability"])
            ],
        ),
    ]
    return lines


def _bands_section(r: dict[str, Any]) -> list[str]:
    b = r["bands"]
    vb, tb = r["validation"]["bands"], r["test"]["bands"]
    rows = []
    for band in ("MEDIUM", "HIGH", "CRITICAL"):
        v, t = vb["at_or_above"][band], tb["at_or_above"][band]
        rows.append(
            [
                f"≥ {band}",
                f"{f(b['recall_targets_on_validation'][band], 2)}",
                f(b["raw"][band], 4),
                str(b.get("risk_score", {}).get(band, "—")),
                f"{f(v['precision'])} / {f(v['recall'])} / {pct(v['flagged_share'])}",
                f"{f(t['precision'])} / {f(t['recall'])} / {pct(t['flagged_share'])}",
            ]
        )
    ex = []
    for band in ("LOW", "MEDIUM", "HIGH", "CRITICAL"):
        v, t = vb["exclusive"][band], tb["exclusive"][band]
        ex.append(
            [
                band,
                f"{pct(v['share'])} / {f(v['failure_rate'])}",
                f"{pct(t['share'])} / {f(t['failure_rate'])}",
            ]
        )
    return [
        "`risk_score` = percentile of the raw score among validation predictions (1,001-point quantile "
        "table in the bundle metadata). Bands are cut on validation by recall targets; cut-points are "
        "stored in the model metadata (`risk_bundle/metadata.json`, MLflow model metadata and version tags).",
        "",
        table(
            [
                "band",
                "recall target (val)",
                "raw cut",
                "risk_score cut",
                "validation precision / recall / flagged",
                "test precision / recall / flagged",
            ],
            rows,
        ),
        "",
        table(
            ["band (exclusive)", "validation share / failure rate", "test share / failure rate"], ex
        ),
    ]


