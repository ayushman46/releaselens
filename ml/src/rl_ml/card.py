def write_docs(docs_dir: Path) -> list[Path]:
    res = load_results(docs_dir)
    docs_dir.mkdir(parents=True, exist_ok=True)
    a = docs_dir / "RESULTS.md"
    b = docs_dir / "MODEL_CARD.md"
    a.write_text(render_results(res))
    b.write_text(render_model_card(res))
    return [a, b]


def main(argv: list[str] | None = None) -> int:
    from rl_ml.train import repo_root

    p = argparse.ArgumentParser(prog="python -m rl_ml.card")
    p.add_argument("--docs-dir", type=Path, default=repo_root() / "docs" / "ml")
    args = p.parse_args(argv)
    for path in write_docs(args.docs_dir):
        sys.stdout.write(f"wrote {path}\n")
    return 0


